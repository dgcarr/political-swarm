"""Pass/fail tests for the twelve evaluator-owned checks.

These checks decide every published benchmark score, so they are graded here the way they grade a
submission: each check is driven with a submission shape it must accept and with the specific defect
it exists to catch, and the defect must produce a recognisable message.

Every expected number is independent of the code under test. The curves are hand-chosen so that the
arithmetic can be stated in a comment and checked by eye, and no expectation is ever produced by
calling `interpolate_linear`, `interpolation_candidates`, `alloy_cross_section` or any other
function a check itself uses. That rule is the whole point of the exercise: the sweep that prompted
these tests shipped a defect behind assertions generated by the implementation under test.
"""

from __future__ import annotations

import hashlib
import struct
import zlib
from pathlib import Path

import pytest

from oracle.checks import OracleChecks
from oracle.reference_data import DamageCurve, DataPoint
from oracle.submission import (
    CalculationObservation,
    CsvTable,
    ProcessObservation,
)


# Fe doubles in energy from 1 to 4 MeV while its cross-section rises tenfold, so the two accepted
# conventions disagree at the midpoint and can be told apart by hand:
#   linear   10 + (2-1)/(4-1) * (100-10) = 10 + 30      = 40
#   log-log  10 * (100/10) ** (ln2/ln4)  = 10 * 10**0.5 = 31.6227766016837933
#   log-lin  10 + (ln2/ln4) * (100-10)   = 10 + 45      = 55      <- rejected by the oracle
FE_AT_2_MEV_LINEAR = 40.0
FE_AT_2_MEV_LOG_LOG = 31.6227766016837933
FE_AT_2_MEV_LOG_LINEAR = 55.0  # linear in log E: 10 + (ln2/ln4)*90
FE_AT_2_MEV_LOG_CROSS_SECTION = 21.5443469003188372  # log sigma linear in E: 10 * 10**(1/3)

CURVES = {
    "Fe": DamageCurve("Fe", (DataPoint(1.0e6, 10.0), DataPoint(4.0e6, 100.0))),
    "Cr": DamageCurve("Cr", (DataPoint(1.0e6, 30.0), DataPoint(4.0e6, 300.0))),
    "Ni": DamageCurve("Ni", (DataPoint(1.0e6, 20.0), DataPoint(4.0e6, 200.0))),
}
FE_MINIMUM_MEV = 1.0

# Atomic fractions of 72/18/10 wt% Fe/Cr/Ni, quoted from the worked example in the task and already
# verified against hand-derived constants by `run_oracle.py --self-test`.
FRACTIONS = {
    "Fe": 0.7139520416796498,
    "Cr": 0.19170020332101848,
    "Ni": 0.09434775499933185,
}

ENERGY_HEADER = "Neutron energy [MeV]"
TOTAL_HEADER = "Total alloy displacement cross-section [dpa-barn]"
RANGE_MESSAGE = "Error: requested energy is outside the supported data range"


class StubRunner:
    """Returns canned observations so a check's logic can be exercised without a real submission."""

    def __init__(
        self,
        observations: dict[str, CalculationObservation] | None = None,
        synthetic: CalculationObservation | None = None,
        provenance_text: str = "",
        test_files: tuple[Path, ...] = (),
        test_run: ProcessObservation | None = None,
        default_run: CalculationObservation | None = None,
    ) -> None:
        self.observations = observations or {}
        self.default_run = default_run
        self.synthetic = synthetic
        self.provenance_text = provenance_text
        self.test_files = test_files
        self.test_run = test_run

    def discover_test_files(self) -> tuple[Path, ...]:
        return self.test_files

    def run_test_suite(self) -> ProcessObservation:
        if self.test_run is None:
            raise AssertionError("test did not stub the test-suite run")
        return self.test_run

    def calculate(self, request) -> CalculationObservation:
        if request.case_id not in self.observations:
            raise AssertionError(f"test did not stub case {request.case_id!r}")
        return self.observations[request.case_id]

    def run_default_command(self) -> CalculationObservation:
        if self.default_run is None:
            raise AssertionError("test did not stub the default-command run")
        return self.default_run

    def calculate_with_synthetic_fe(self, request) -> CalculationObservation:
        if self.synthetic is None:
            raise AssertionError("test did not stub the synthetic-Fe observation")
        return self.synthetic

    def run_module_arguments(self, arguments) -> ProcessObservation:
        return ProcessObservation(("python", *arguments), 1, self.provenance_text, "")

    def read_provenance_artifacts(self) -> tuple[str, ...]:
        return ()


def table(
    rows: tuple[dict[str, float], ...],
    headers: tuple[str, ...] | None = None,
    printed: tuple[dict[str, str], ...] = (),
) -> CsvTable:
    return CsvTable(Path("result.csv"), headers or (ENERGY_HEADER, TOTAL_HEADER), rows, printed)


def curve_rows(pairs: tuple[tuple[float, float], ...]) -> tuple[dict[str, float], ...]:
    return tuple({ENERGY_HEADER: energy, TOTAL_HEADER: total} for energy, total in pairs)


def observation(
    return_code: int = 0,
    output: str = "",
    tables: tuple[CsvTable, ...] = (),
    images: tuple[Path, ...] = (),
) -> CalculationObservation:
    process = ProcessObservation(("python", "-m", "alloydamage"), return_code, output, "")
    return CalculationObservation(process, Path("case"), tables, images, ())


def checks_for(
    case: str | None = None,
    result: CalculationObservation | None = None,
    *,
    synthetic: CalculationObservation | None = None,
    provenance_text: str = "",
    submission_root: Path = Path("submission"),
    test_files: tuple[Path, ...] = (),
    test_run: ProcessObservation | None = None,
    default_run: CalculationObservation | None = None,
) -> OracleChecks:
    observations = {case: result} if case is not None and result is not None else {}
    runner = StubRunner(observations, synthetic, provenance_text, test_files, test_run, default_run)
    return OracleChecks(runner, dict(CURVES), submission_root)


def failure(check) -> str:
    with pytest.raises(AssertionError) as caught:
        check()
    return str(caught.value)


