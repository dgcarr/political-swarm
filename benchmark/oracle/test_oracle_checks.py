# --------------------------------------------------------------------------------------------
# Substituting a data file keeps the clone's own provenance consistent
# --------------------------------------------------------------------------------------------

def test_substituting_a_data_file_rewrites_the_digest_the_clone_records(tmp_path: Path) -> None:
    """A submission that verifies its inputs must not be punished for doing so.

    The interpolation check swaps in a synthetic curve. Before this, a submission that checked its
    data by digest — as this evaluator does — would refuse the swap and fail a check about
    interpolation, not integrity.
    """
    from oracle.submission import _substitute_data_file

    data = tmp_path / "data" / "Fe"
    data.mkdir(parents=True)
    csv_path = data / "Fe_dpa_nrt.csv"
    csv_path.write_text("energy_eV,displacement_xs_barn\n95,0.07\n", encoding="utf-8")
    original = hashlib.sha256(csv_path.read_bytes()).hexdigest()
    provenance = data / "PROVENANCE.md"
    provenance.write_text(f"Source: IAEA\nSHA-256: {original}\n", encoding="utf-8")
    unrelated = data / "NOTES.md"
    unrelated.write_text("nothing to rewrite here\n", encoding="utf-8")

    replacement = "energy_eV,displacement_xs_barn\n1000000,10\n100000000,1000\n"
    _substitute_data_file(tmp_path, csv_path, replacement)

    assert csv_path.read_text(encoding="utf-8") == replacement
    expected = hashlib.sha256(replacement.encode("utf-8")).hexdigest()
    assert provenance.read_text(encoding="utf-8") == f"Source: IAEA\nSHA-256: {expected}\n"
    assert unrelated.read_text(encoding="utf-8") == "nothing to rewrite here\n"


