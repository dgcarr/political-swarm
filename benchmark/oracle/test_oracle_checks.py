# 7. No extrapolation
# --------------------------------------------------------------------------------------------
# The probe asks for 1e-5 to 1e-4 MeV in two points. It straddles the data's minimum: with two
# points every spacing convention emits exactly the endpoints, and only the upper one is supported.

PROBE_LOW_MEV = 1.0e-5
PROBE_HIGH_MEV = 1.0e-4


def no_extrapolation_checks(result: CalculationObservation) -> OracleChecks:
    checks = checks_for("no-extrapolation", result)
    # A minimum between the two probe endpoints, matching the real Fe data's 9.5e-5 MeV.
    checks.curves = {**CURVES, "Fe": DamageCurve("Fe", (DataPoint(95.0, 0.07), DataPoint(4.0e6, 100.0)))}
    return checks


def test_no_extrapolation_accepts_a_refusal_that_explains_the_range() -> None:
    result = observation(return_code=1, output=RANGE_MESSAGE)
    assert "refused/flagged" in no_extrapolation_checks(result)._check_no_extrapolation()


def test_no_extrapolation_accepts_a_refusal_naming_the_range_before_outside() -> None:
    # Verbatim from the 2026-10-08 capitalist-luna arm, which every earlier pattern missed on word order.
    message = "alloydamage: error: Requested range [10, 100] is outside supported intersection [95, 3e+07]"
    result = observation(return_code=2, output=message)
    assert "refused/flagged" in no_extrapolation_checks(result)._check_no_extrapolation()


def test_no_extrapolation_accepts_emitting_only_the_supported_endpoint() -> None:
    result = observation(0, RANGE_MESSAGE, (table(curve_rows(((PROBE_HIGH_MEV, 0.07),))),))
    assert "refused/flagged" in no_extrapolation_checks(result)._check_no_extrapolation()


def test_no_extrapolation_rejects_values_below_the_native_minimum() -> None:
    result = observation(
        0, RANGE_MESSAGE, (table(curve_rows(((PROBE_LOW_MEV, 0.01), (PROBE_HIGH_MEV, 0.07)))),)
    )
    assert "silently extrapolated" in failure(
        no_extrapolation_checks(result)._check_no_extrapolation
    )


def test_no_extrapolation_rejects_a_request_clamped_into_range() -> None:
    # Regression: a clamped row sits AT the minimum, not below it, so the below-minimum guard alone
    # let this through while the arm reported "clipped".
    clamped = 95.0 / 1.0e6
    result = observation(
        0, "clipped to the minimum energy", (table(curve_rows(((clamped, 0.07), (PROBE_HIGH_MEV, 0.07)))),)
    )
    detail = failure(no_extrapolation_checks(result)._check_no_extrapolation)
