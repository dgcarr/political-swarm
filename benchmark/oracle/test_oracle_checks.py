def test_blocked_checks_separates_an_unrun_program_from_a_wrong_answer() -> None:
    from oracle.report import CheckResult, blocked_checks

    results = [
        CheckResult(1, "Pure-Fe", True, "ok"),
        CheckResult(2, "Mixture", False, "calculation exited 1: Traceback ..."),
        CheckResult(3, "Conversion", False, "inferred Fe atomic fraction: got 0.72 ..."),
        CheckResult(8, "CSV", False, "no numeric result CSV with MeV energy ..."),
    ]
    assert [result.id for result in blocked_checks(results)] == [2, 8]


def test_two_number_summary_reports_running_and_the_judged_score_apart() -> None:
    from oracle.report import CheckResult, two_number_summary

    crashed = [CheckResult(i, "c", False, "calculation exited 1: Traceback ...") for i in range(1, 11)]
    assert two_number_summary(crashed + [CheckResult(11, "c", True, "ok"), CheckResult(12, "c", False, "wrong")]) == (
        "runs: no (10 blocked) · functional 1/2"
    )
    running = [CheckResult(i, "c", True, "ok") for i in range(1, 12)] + [CheckResult(12, "c", False, "wrong")]
    assert two_number_summary(running) == "runs: yes · functional 11/12"


def test_a_program_that_cannot_run_pure_fe_blocks_every_check_that_runs_it() -> None:
    from oracle.report import CheckResult, blocked_checks

    crash = "calculation exited 1: Traceback ..."
    results = [
        CheckResult(1, "Pure-Fe", False, crash),
        CheckResult(5, "Unsupported element", False, "failure did not clearly identify unsupported Cu"),
        CheckResult(9, "Plot", False, "calculation produced no PNG file"),
        CheckResult(10, "Log axis", False, "no log-scale call found"),
        CheckResult(12, "Own tests", False, "the submission's own test suite fails (exit 1)"),
    ]
    assert [result.id for result in blocked_checks(results)] == [1, 5, 9]
    # With pure Fe running, a missing plot is judged on its own merits.
    running = [CheckResult(1, "Pure-Fe", True, "ok"), CheckResult(3, "Conversion", False, crash), results[2]]
    assert [result.id for result in blocked_checks(running)] == [3]


