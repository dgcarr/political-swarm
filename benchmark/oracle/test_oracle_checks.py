# 3 and 8. Inferred atomic fractions, and the CSV schema
# --------------------------------------------------------------------------------------------

CONTRIBUTION_HEADERS = {
    "Fe": "Fe contribution [dpa-barn]",
    "Cr": "Cr contribution [dpa-barn]",
    "Ni": "Ni contribution [dpa-barn]",
}
SCHEMA_HEADERS = (ENERGY_HEADER, *CONTRIBUTION_HEADERS.values(), TOTAL_HEADER)


def schema_rows(scale: dict[str, float]) -> tuple[dict[str, float], ...]:
    """Rows at the two curve endpoints, where no interpolation is involved at all.

    At 1 MeV the curves read Fe 10, Cr 30, Ni 20 barn and at 4 MeV ten times that, so each
    contribution is a fraction times a literal endpoint and the total is their sum.
    """
    rows = []
    for energy, (fe, cr, ni) in ((1.0, (10.0, 30.0, 20.0)), (4.0, (100.0, 300.0, 200.0))):
        contributions = {
            "Fe": FRACTIONS["Fe"] * fe * scale.get("Fe", 1.0),
            "Cr": FRACTIONS["Cr"] * cr * scale.get("Cr", 1.0),
            "Ni": FRACTIONS["Ni"] * ni * scale.get("Ni", 1.0),
        }
        row = {ENERGY_HEADER: energy, TOTAL_HEADER: sum(contributions.values())}
        row.update({CONTRIBUTION_HEADERS[element]: value for element, value in contributions.items()})
        rows.append(row)
    return tuple(rows)


def test_weight_conversion_accepts_correct_atomic_fractions() -> None:
    result = observation(tables=(table(schema_rows({}), SCHEMA_HEADERS),))
    assert "Fe=0.71395204" in checks_for("simplified-304l", result)._check_weight_conversion()


def test_weight_conversion_rejects_mass_fractions_used_as_atomic_fractions() -> None:
    # 72 wt% Fe read straight through as an atomic fraction: 0.72 / 0.7139520 = 1.00847.
    result = observation(tables=(table(schema_rows({"Fe": 0.72 / FRACTIONS["Fe"]}), SCHEMA_HEADERS),))
    assert "inferred Fe atomic fraction: got 0.72" in failure(
        checks_for("simplified-304l", result)._check_weight_conversion
    )


def test_weight_conversion_ignores_the_interpolation_convention_between_nodes() -> None:
    """The decoupling: composition is judged only where every convention agrees.

    Rows at 1 and 4 MeV sit on tabulated points, so the ratio there is the atomic fraction whatever
    the submission does in between. The 2 MeV row carries the rejected log-linear value and must not
    be what this check is deciding on — that is check 1's job, and counting it twice made one defect
    cost four checks.
    """
    interior = {
        ENERGY_HEADER: 2.0,
        TOTAL_HEADER: FE_AT_2_MEV_LOG_LINEAR,
        **{header: FE_AT_2_MEV_LOG_LINEAR / 3.0 for header in CONTRIBUTION_HEADERS.values()},
    }
    node_rows = schema_rows({})
    result = observation(tables=(table((node_rows[0], interior, node_rows[1]), SCHEMA_HEADERS),))
    assert "Fe=0.71395204" in checks_for("simplified-304l", result)._check_weight_conversion()


def test_weight_conversion_refuses_a_table_with_no_row_on_a_tabulated_energy() -> None:
    rows = ({
        ENERGY_HEADER: 2.0,
        TOTAL_HEADER: FE_AT_2_MEV_LINEAR,
        **{header: FE_AT_2_MEV_LINEAR / 3.0 for header in CONTRIBUTION_HEADERS.values()},
    },)
    assert "no emitted row lies on an energy the reference data tabulates" in failure(
        checks_for("simplified-304l", observation(tables=(table(rows, SCHEMA_HEADERS),)))._check_weight_conversion
    )


def test_normalisation_accepts_a_correctly_renormalised_composition() -> None:
    # 71.5/18.2/10.1 wt% over CIAAW weights 55.845, 51.9961, 58.6934:
    #   moles 1.2803294..., 0.3500266..., 0.1720823..., summing to 1.8024384...
    # so the atomic fractions below, which must come out of the emitted contributions unchanged
    # even though the supplied weights total 99.8% rather than 100%.
    renormalised = {"Fe": 0.7103326778694977, "Cr": 0.19419617224393554, "Ni": 0.09547114988656669}
    rows = []
    for energy, (fe, cr, ni) in ((1.0, (10.0, 30.0, 20.0)), (4.0, (100.0, 300.0, 200.0))):
        contributions = {
            "Fe": renormalised["Fe"] * fe,
            "Cr": renormalised["Cr"] * cr,
            "Ni": renormalised["Ni"] * ni,
        }
        row = {ENERGY_HEADER: energy, TOTAL_HEADER: sum(contributions.values())}
        row.update({CONTRIBUTION_HEADERS[e]: v for e, v in contributions.items()})
        rows.append(row)
    result = observation(tables=(table(tuple(rows), SCHEMA_HEADERS),))
    assert "normalized correctly" in checks_for("normalisation", result)._check_normalisation()


def test_normalisation_rejects_weights_carried_through_without_renormalising() -> None:
    # 71.5 wt% Fe read straight through as an atomic fraction instead of 0.71033.
    scale = 0.715 / FRACTIONS["Fe"]
    result = observation(tables=(table(schema_rows({"Fe": scale}), SCHEMA_HEADERS),))
    assert "inferred Fe atomic fraction: got 0.715" in failure(
        checks_for("normalisation", result)._check_normalisation
    )


def test_csv_output_accepts_unit_bearing_headers_and_correct_values() -> None:
    result = observation(tables=(table(schema_rows({}), SCHEMA_HEADERS),))
    assert "2 independently computed rows" in checks_for("simplified-304l", result)._check_csv_output()


def test_csv_output_rejects_cross_section_columns_without_units() -> None:
    headers = (ENERGY_HEADER, "Fe contribution", "Cr contribution", "Ni contribution", TOTAL_HEADER)
    rows = tuple(
        {
            ENERGY_HEADER: row[ENERGY_HEADER],
            TOTAL_HEADER: row[TOTAL_HEADER],
            **{
                f"{element} contribution": row[CONTRIBUTION_HEADERS[element]]
                for element in CONTRIBUTION_HEADERS
            },
        }
        for row in schema_rows({})
    )
    result = observation(tables=(table(rows, headers),))
    assert "do not state barn/dpa-barn units" in failure(
        checks_for("simplified-304l", result)._check_csv_output
    )


def test_csv_output_rejects_contributions_that_do_not_sum_to_the_total() -> None:
    rows = tuple({**row, TOTAL_HEADER: row[TOTAL_HEADER] * 1.5} for row in schema_rows({}))
    result = observation(tables=(table(rows, SCHEMA_HEADERS),))
    detail = failure(checks_for("simplified-304l", result)._check_csv_output)
    assert "alloy total" in detail or "sum of contribution columns" in detail


