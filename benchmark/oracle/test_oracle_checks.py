def png_bytes(width: int = 8, height: int = 8, padding: int = 2048) -> bytes:
    def chunk(kind: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + kind
            + data
            + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)
        )

    scanlines = b"".join(b"\x00" + b"\x7f" * (width * 3) for _ in range(height))
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 2, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(scanlines))
        + chunk(b"tEXt", b"pad\x00" + b"x" * padding)
        + chunk(b"IEND", b"")
    )


def test_plot_generation_accepts_a_valid_png(tmp_path: Path) -> None:
    path = tmp_path / "result.png"
    path.write_bytes(png_bytes())
    result = observation(images=(path,))
