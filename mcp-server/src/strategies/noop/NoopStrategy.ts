import type { SwarmStrategy, EngineContext } from '../../engine/SwarmStrategy.js';
import { emptyGraph, addNode } from '../../engine/TaskGraph.js';
import type { Assignment, Decision, ReviewResult, TaskGraph, TaskSpec, TestResult, WorkProduct } from '../../engine/types.js';
import {
  stubAccept,
  stubDeclareOwnership,
  stubDisposeFindings,
  stubIntegrate,
  stubRemediate,
  stubVerifyDelivery,
} from '../../engine/barrierStubs.js';
import { toEvidenceItems } from '../evidenceMandate.js';

/**
 * Milestone-1 scaffolding strategy: deterministic, makes no OpenRouter calls, always approves.
 * Exists purely to exercise SwarmEngine + RepoWorktree + Ledger + BudgetGuard end-to-end
 * (worktree creation, FileOp application, diff, decision recording) without needing an API key.
 */
export class NoopStrategy implements SwarmStrategy {
  readonly id = 'noop' as const;

  async plan(ctx: EngineContext, task: TaskSpec): Promise<TaskGraph> {
    // Every doctrine records a test mandate before implementation, and the acceptance barrier
    // refuses a criterion with none. Map each criterion to the first required check, so the smoke
    // path reaches acceptance on real check evidence rather than on an exemption.
    const check = ctx.checks.categories.find((c) => c.required);
    ctx.runState.evidence = toEvidenceItems(
      {
        evidence: task.acceptanceCriteria.map((criterion) => ({
          criterion,
          checkCategoryId: check?.id ?? null,
          expectedResult: 'the check passes on the integrated tree',
          ...(check ? {} : { manualInspection: 'Inspect the worktree for the sentinel file.' }),
        })),
      },
      task.acceptanceCriteria,
      ctx.checks.categories,
    );

    const graph = emptyGraph();
    addNode(graph, {
      id: 'sentinel',
      title: 'Write sentinel file',
      description: `Noop smoke-test task for goal: ${task.goal}`,
      acceptanceCriteria: task.acceptanceCriteria,
      dependsOn: [],
      targetGlobs: ['SWARM_SENTINEL.md'],
      riskTags: [],
      riskClass: 'low',
      phase: 'queued',
      attempts: [],
    });
    return graph;
  }

  async assign(_ctx: EngineContext, graph: TaskGraph): Promise<Assignment[]> {
    return graph.order
      .filter((id) => graph.nodes[id].phase === 'queued')
      .map((id) => ({ taskId: id, assigneeId: 'noop-agent', role: 'noop' }));
  }

  async execute(ctx: EngineContext, assignment: Assignment): Promise<WorkProduct> {
    const node = ctx.runState.graph!.nodes[assignment.taskId];
    return {
      taskId: assignment.taskId,
      assignment,
      fileOps: [
        {
          op: 'write',
          path: 'SWARM_SENTINEL.md',
          content: `# Swarm sentinel\n\nGoal: ${ctx.runState.task.goal}\nTask: ${node.title}\nGenerated by NoopStrategy for engine smoke-testing.\n`,
        },
      ],
      rationale: 'Deterministic sentinel write for engine smoke-testing.',
    };
  }

  async review(_ctx: EngineContext, product: WorkProduct, test: TestResult): Promise<ReviewResult> {
    return {
      taskId: product.taskId,
      findings: [{ reviewerId: 'noop-agent', verdict: 'approve', rationale: 'Noop strategy always approves.' }],
      testResult: test,
    };
  }

  async decide(_ctx: EngineContext, product: WorkProduct, review: ReviewResult): Promise<Decision> {
    return { taskId: product.taskId, outcome: 'approved', rationale: 'Noop strategy always approves.', evidenceRefs: [], meta: { review } };
  }

  async recordOutcome(): Promise<void> {
    // No accounting to update.
  }

  requiresHumanApproval(): boolean {
    return false;
  }

  // ---------- acceptance barriers ----------
  // Deterministic and always-passing, like the rest of this strategy: its only job is to keep the
  // no-API-key smoke path exercising the engine's full barrier sequence.

  declareOwnership = stubDeclareOwnership;
  integrate = stubIntegrate;
  verifyDelivery = stubVerifyDelivery;
  disposeFindings = stubDisposeFindings;
  accept = stubAccept;
  remediate = stubRemediate;
}
